"""Spherical Bessel functions: from SymPy to an oscilloscope screen.

MATH (SymPy)
  ODE:      x^2 y'' + 2 x y' + (x^2 - n(n+1)) y = 0
  Rayleigh: j_n(x) = (-x)^n (1/x d/dx)^n (sin x / x)
  small x:  j_n ~ x^n / (2n+1)!!          large x:  j_n ~ sin(x - n pi/2) / x
  physics:  radial waves of the Helmholtz equation in spheres -- Mie scattering,
            spherical antennas, and the particle in a spherical box (quantum dots).

HARDWARE (EE)
  An AWG / microcontroller DAC plays j_n as a voltage: x maps to time, the
  waveform is offset/scaled into [0, V_ref], quantized to N bits, held for one
  sample period (zero-order hold) and seen through the scope's input bandwidth
  (first-order RC low-pass, f_3dB). Quantization noise ~ LSB / sqrt(12).
  lut_header() writes a C lookup table for a microcontroller (RP2040, ESP32,
  STM32 ...); usb_budget() checks whether live streaming fits a USB link.
  USB-C itself is just the connector: the data rate is set by the USB version
  (full-speed 12 Mbit/s on most hobby MCUs), and default USB-C power is 5 V.
"""
import numpy as np
import sympy as sp
from scipy.special import spherical_jn

xs = sp.Symbol("x", positive=True)


# ── math ─────────────────────────────────────────────────────────────

def rayleigh_jn(n):
    """j_n by Rayleigh's formula, simplified."""
    if n < 0 or int(n) != n:
        raise ValueError("n must be a non-negative integer")
    f = sp.sin(xs) / xs
    for _ in range(n):
        f = sp.diff(f, xs) / xs
    return sp.simplify((-xs) ** n * f)


def ode_residual(n):
    y = rayleigh_jn(n)
    r = xs ** 2 * sp.diff(y, xs, 2) + 2 * xs * sp.diff(y, xs) + (xs ** 2 - n * (n + 1)) * y
    return sp.simplify(r)


def small_x_leading(n):
    """Leading Taylor term x^n / (2n+1)!!."""
    return xs ** n / sp.factorial2(2 * n + 1)


def taylor(n, order=8):
    return sp.series(rayleigh_jn(n), xs, 0, order)


def asymptotic(n):
    return sp.sin(xs - n * sp.pi / 2) / xs


def recurrence_residual(n):
    """j_{n-1} + j_{n+1} = (2n+1)/x j_n."""
    return sp.simplify(rayleigh_jn(n - 1) + rayleigh_jn(n + 1) - (2 * n + 1) / xs * rayleigh_jn(n))


# ── signal chain ─────────────────────────────────────────────────────

def waveform(n, x_max=30.0, period_s=1e-3, fs=1e6):
    """Map x in [0, x_max] onto one period (seconds) sampled at fs. Returns (t, x, j_n)."""
    if x_max <= 0 or period_s <= 0 or fs <= 0:
        raise ValueError("x_max, period and fs must be positive")
    n_samples = int(round(period_s * fs))           # integer count: arange with a float step can add one
    t = np.arange(n_samples) / fs
    x = t / period_s * x_max
    return t, x, spherical_jn(n, x)


def to_dac_codes(y, bits=12, lo=-0.25, hi=1.0):
    """Affine map [lo, hi] -> [0, 2^bits - 1], round, clip. j_n lies in about [-0.22, 1]."""
    if not 1 <= bits <= 24:
        raise ValueError("bits must be in 1..24")
    full = 2 ** bits - 1
    return np.clip(np.round((np.asarray(y) - lo) / (hi - lo) * full), 0, full).astype(np.int64)


def codes_to_volts(codes, bits=12, vref=3.3):
    return codes / (2 ** bits - 1) * vref


def scope_view(v, fs, bandwidth_hz, noise_v=0.0, seed=0):
    """First-order RC low-pass (the probe/scope bandwidth) + optional white noise."""
    if bandwidth_hz <= 0:
        raise ValueError("bandwidth must be positive")
    a = 1 - np.exp(-2 * np.pi * bandwidth_hz / fs)
    out = np.empty_like(np.asarray(v, float))
    acc = float(v[0])
    for i, s in enumerate(v):
        acc += a * (s - acc)
        out[i] = acc
    return out + noise_v * np.random.default_rng(seed).standard_normal(out.size)


def quantization_rms_error(y, bits, lo=-0.25, hi=1.0):
    """Measured RMS error (in y units) vs the LSB/sqrt(12) theory."""
    codes = to_dac_codes(y, bits, lo, hi)
    yq = lo + codes / (2 ** bits - 1) * (hi - lo)
    lsb = (hi - lo) / (2 ** bits - 1)
    return float(np.sqrt(np.mean((yq - y) ** 2))), lsb / np.sqrt(12)


# ── hardware artefacts ───────────────────────────────────────────────

def lut_header(n, size=256, bits=12, x_max=30.0, name=None):
    """C header with a const uint16_t table of j_n for a microcontroller DAC."""
    if not 2 <= size <= 65536:
        raise ValueError("size must be in 2..65536")
    name = name or f"SPH_J{n}_LUT"
    x = np.linspace(0, x_max, size, endpoint=False)
    codes = to_dac_codes(spherical_jn(n, x), bits)
    body = ",\n".join("    " + ", ".join(f"{c:4d}" for c in codes[i:i + 12]) for i in range(0, size, 12))
    return (f"/* j_{n}(x), x in [0, {x_max}), {size} samples, {bits}-bit DAC codes.\n"
            f"   Generated by dgs/spherical_bessel_scope.py. code = round((j - (-0.25)) / 1.25 * {2**bits - 1}). */\n"
            f"#ifndef {name}_H\n#define {name}_H\n#include <stdint.h>\n"
            f"#define {name}_SIZE {size}\n#define {name}_BITS {bits}\n"
            f"static const uint16_t {name}[{size}] = {{\n{body}\n}};\n#endif\n"), codes


def usb_budget(fs, bits, channels=1, link_bps=12e6, efficiency=0.6):
    """Can a USB link stream the samples live? efficiency covers protocol overhead
    (an ASSUMPTION; full-speed bulk transfers usually net well under 12 Mbit/s).
    Samples are sent as whole bytes."""
    bytes_per_sample = int(np.ceil(bits / 8))
    need = fs * channels * bytes_per_sample * 8
    have = link_bps * efficiency
    return {"needed Mbit/s": need / 1e6, "available Mbit/s": have / 1e6, "fits": need <= have}


# ── quantum link: particle in a spherical box ───────────────────────

def spherical_box_levels(l_max=2, n_max=3, a_nm=2.0, m_eff=1.0):
    """E_{n,l} = hbar^2 beta_{n,l}^2 / (2 m a^2) in eV, beta = zeros of j_l (via griffiths.bessel)."""
    from griffiths.bessel import spherical_well_zeros
    hbar, me, ev = 1.054571817e-34, 9.1093837015e-31, 1.602176634e-19
    a = a_nm * 1e-9
    out = []
    for l in range(l_max + 1):
        for k, b in enumerate(spherical_well_zeros(l, n_max), start=1):
            out.append((hbar ** 2 * b ** 2 / (2 * m_eff * me * a ** 2) / ev, k, l, b))
    return sorted(out)
